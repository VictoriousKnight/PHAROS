def dataset_records(
    dataset: Dataset,
) -> list[DatasetRecord]:
    records = getattr(
        dataset,
        "records",
        None,
    )

    if records is None:
        try:
            records = list(dataset)
        except TypeError:
            records = []

    records = list(records)

    if not records:
        raise TrainingDataError("Dataset contains no records.")

    return records


def validate_training_labels(
    records: Sequence[DatasetRecord],
) -> tuple[
    list[int],
    int,
    int,
]:
    targets: list[int] = []

    for index, record in enumerate(records):
        label = getattr(
            record,
            "label",
            None,
        )

        if label is None:
            raise TrainingDataError(f"Record {index} has no label.")

        try:
            targets.append(label_to_binary(label))
        except TrainingDataError as exc:
            raise TrainingDataError(f"Invalid label at record {index}: {exc}") from exc

    positive = sum(targets)

    negative = len(targets) - positive

    if positive == 0:
        raise TrainingDataError("Dataset contains no malicious/positive samples.")

    if negative == 0:
        raise TrainingDataError("Dataset contains no benign/negative samples.")

    return (
        targets,
        positive,
        negative,
    )



def load_training_dataset(
    path: Path,
) -> Dataset:
    LOGGER.info(
        "Loading dataset: %s",
        path,
    )

    try:
        dataset = load_dataset(path)
    except Exception as exc:
        raise TrainingDataError(f"Unable to load dataset {path}: {exc}") from exc

    if dataset is None:
        raise TrainingDataError("Dataset loader returned no dataset.")

    try:
        valid = validate_dataset(dataset)

        if valid is False:
            raise TrainingDataError("Dataset validation failed.")

    except TypeError:
        try:
            valid = validate_dataset(
                dataset,
                require_labels=True,
            )

            if valid is False:
                raise TrainingDataError("Dataset validation failed.")
        except Exception as exc:
            raise TrainingDataError(f"Dataset validation failed: {exc}") from exc
    except Exception as exc:
        raise TrainingDataError(f"Dataset validation failed: {exc}") from exc

    return dataset



def build_training_matrix(
    dataset: Dataset,
) -> tuple[
    Any,
    Any,
    list[str],
]:
    """
    Build X/y using the canonical dataset layer.

    build_ml_inputs is preferred because it keeps the training script aligned
    with prediction-time feature handling.
    """

    try:
        result = build_ml_inputs(
            dataset,
            require_labels=True,
        )
    except TypeError:
        try:
            result = build_ml_inputs(dataset)
        except Exception as exc:
            raise TrainingDataError(f"Unable to build ML inputs: {exc}") from exc
    except Exception as exc:
        raise TrainingDataError(f"Unable to build ML inputs: {exc}") from exc

    if not isinstance(
        result,
        tuple,
    ):
        raise TrainingDataError("build_ml_inputs returned an unsupported value.")

    if len(result) < 2:
        raise TrainingDataError("build_ml_inputs did not return X and y.")

    x = result[0]
    y = result[1]

    ids: list[str] = []

    if len(result) >= 3:
        possible_ids = result[2]

        if isinstance(
            possible_ids,
            Sequence,
        ) and not isinstance(
            possible_ids,
            (str, bytes),
        ):
            ids = [str(value) for value in possible_ids]

    try:
        x_array = np.asarray(
            x,
            dtype=np.float64,
        )
    except Exception as exc:
        raise TrainingDataError(
            f"Unable to convert feature matrix to numpy array: {exc}"
        ) from exc

    try:
        y_array = np.asarray(y)
    except Exception as exc:
        raise TrainingDataError(
            f"Unable to convert targets to numpy array: {exc}"
        ) from exc

    if x_array.ndim != 2:
        raise TrainingDataError(
            f"Feature matrix must be 2-dimensional; " f"received shape {x_array.shape}."
        )

    if y_array.ndim != 1:
        y_array = y_array.reshape(-1)

    if x_array.shape[0] != y_array.shape[0]:
        raise TrainingDataError(
            "Feature matrix and target vector have different " "numbers of samples."
        )

    if x_array.shape[0] == 0:
        raise TrainingDataError("Feature matrix contains no samples.")

    if x_array.shape[1] == 0:
        raise TrainingDataError("Feature matrix contains no features.")

    if x_array.shape[1] > MAX_FEATURES:
        raise TrainingDataError(
            f"Feature matrix contains {x_array.shape[1]:,} features, "
            f"exceeding {MAX_FEATURES:,}."
        )

    if x_array.shape[0] > MAX_SAMPLES:
        raise TrainingDataError(
            f"Feature matrix contains {x_array.shape[0]:,} samples, "
            f"exceeding {MAX_SAMPLES:,}."
        )

    x_array = np.nan_to_num(
        x_array,
        nan=0.0,
        posinf=0.0,
        neginf=0.0,
    )

    binary_targets: list[int] = []

    for value in y_array.tolist():
        binary_targets.append(label_to_binary(value))

    y_array = np.asarray(
        binary_targets,
        dtype=np.int64,
    )

    if not ids:
        records = dataset_records(dataset)

        ids = [
            str(
                getattr(
                    record,
                    "sample_id",
                    index,
                )
            )
            for index, record in enumerate(records)
        ]

    if len(ids) != x_array.shape[0]:
        ids = [str(index) for index in range(x_array.shape[0])]

    return (
        x_array,
        y_array,
        ids,
    )


# ---------------------------------------------------------------------------
# Deterministic split
# ---------------------------------------------------------------------------


def stratified_split_indices(
    y: Any,
    *,
    test_size: float,
    random_state: int,
) -> tuple[
    list[int],
    list[int],
]:
    """
    Deterministic stratified split without depending on sklearn's splitter.

    This keeps the train/test split stable across compatible sklearn versions.
    """

    labels = [int(value) for value in y.tolist()]

    rng = random.Random(random_state)

    by_class: dict[int, list[int]] = {}

    for index, label in enumerate(labels):
        by_class.setdefault(
            label,
            [],
        ).append(index)

    if len(by_class) < 2:
        raise TrainingDataError("Both benign and malicious classes are required.")

    train_indices: list[int] = []
    test_indices: list[int] = []

    for label in sorted(by_class):
        indices = list(by_class[label])

        rng.shuffle(indices)

        count = len(indices)

        test_count = int(math.ceil(count * test_size))

        if count >= 2:
            test_count = max(
                1,
                min(
                    count - 1,
                    test_count,
                ),
            )
        else:
            raise TrainingDataError(
                f"Class {label} contains only one sample; "
                "at least two samples per class are required."
            )

        test_indices.extend(indices[:test_count])

        train_indices.extend(indices[test_count:])

    rng.shuffle(train_indices)

    rng.shuffle(test_indices)

    if not train_indices:
        raise TrainingDataError("Training split is empty.")

    if not test_indices:
        raise TrainingDataError("Test split is empty.")

    return (
        train_indices,
        test_indices,
    )



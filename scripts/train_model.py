def validate_config(
    config: TrainingConfig,
) -> None:
    if not config.dataset_path.exists():
        raise TrainingConfigurationError(
            f"Dataset does not exist: " f"{config.dataset_path}"
        )

    if config.test_size <= 0.0:
        raise TrainingConfigurationError("test_size must be greater than 0.")

    if config.test_size >= 1.0:
        raise TrainingConfigurationError("test_size must be less than 1.")

    if config.n_estimators <= 0:
        raise TrainingConfigurationError("n_estimators must be greater than zero.")

    if config.max_depth is not None and config.max_depth <= 0:
        raise TrainingConfigurationError("max_depth must be positive or None.")

    if config.min_samples_split < 2:
        raise TrainingConfigurationError("min_samples_split must be at least 2.")

    if config.min_samples_leaf <= 0:
        raise TrainingConfigurationError("min_samples_leaf must be positive.")

    if not 0.0 <= config.threshold <= 1.0:
        raise TrainingConfigurationError("threshold must be between 0 and 1.")

    if config.min_samples < 2:
        raise TrainingConfigurationError("min_samples must be at least 2.")

    if config.max_samples < config.min_samples:
        raise TrainingConfigurationError("max_samples must be >= min_samples.")

    if config.max_features_allowed <= 0:
        raise TrainingConfigurationError("max_features_allowed must be positive.")



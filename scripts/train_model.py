def dataset_statistics_safe(
    dataset: Dataset,
) -> dict[str, Any]:
    try:
        statistics = dataset_statistics(dataset)

        if is_dataclass(statistics):
            value = asdict(statistics)
        elif hasattr(
            statistics,
            "to_dict",
        ):
            value = statistics.to_dict()
        elif isinstance(
            statistics,
            Mapping,
        ):
            value = dict(statistics)
        else:
            value = {"value": str(statistics)}

        return json_safe(value)

    except Exception as exc:
        LOGGER.warning(
            "Unable to collect dataset statistics: %s",
            exc,
        )

        return {}


def json_safe(
    value: Any,
    *,
    depth: int = 0,
    max_depth: int = 12,
) -> Any:
    if depth > max_depth:
        return "<max-depth>"

    if value is None:
        return None

    if isinstance(
        value,
        (str, int, bool),
    ):
        return value

    if isinstance(
        value,
        float,
    ):
        return value if math.isfinite(value) else None

    if isinstance(
        value,
        Path,
    ):
        return str(value)

    if is_dataclass(value):
        return json_safe(
            asdict(value),
            depth=depth + 1,
            max_depth=max_depth,
        )

    if isinstance(
        value,
        Mapping,
    ):
        return {
            str(key): json_safe(
                item,
                depth=depth + 1,
                max_depth=max_depth,
            )
            for key, item in list(value.items())[:10_000]
        }

    if isinstance(
        value,
        (list, tuple, set, frozenset),
    ):
        return [
            json_safe(
                item,
                depth=depth + 1,
                max_depth=max_depth,
            )
            for item in list(value)[:10_000]
        ]

    return str(value)



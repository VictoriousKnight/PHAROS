def train_model(
    config: TrainingConfig,
) -> TrainingResult:
    """
    Execute one complete deterministic training run.
    """

    validate_config(config)

    validate_dependencies()

    started = time.monotonic()

    LOGGER.info("Loading training dataset.")

    dataset = load_training_dataset(config.dataset_path)

    records = dataset_records(dataset)

    if len(records) < config.min_samples:
        raise TrainingDataError(
            f"Dataset contains {len(records):,} records; "
            f"at least {config.min_samples:,} are required."
        )

    targets, positive_count, negative_count = validate_training_labels(records)

    LOGGER.info(
        "Dataset contains %d samples " "(benign=%d, malicious=%d).",
        len(records),
        negative_count,
        positive_count,
    )

    schema = build_training_schema(records)

    schema_names = schema_feature_names(schema)

    LOGGER.info(
        "Feature schema contains %d features.",
        len(schema_names),
    )

    x, y, sample_ids = build_training_matrix(dataset)

    if x.shape[1] != len(schema_names):
        LOGGER.warning(
            "Schema feature count (%d) differs from " "matrix feature count (%d).",
            len(schema_names),
            x.shape[1],
        )

    feature_count = int(x.shape[1])

    if feature_count < MIN_FEATURES:
        raise TrainingDataError("At least one feature is required.")

    train_indices, test_indices = stratified_split_indices(
        y,
        test_size=config.test_size,
        random_state=config.random_state,
    )

    x_train = x[train_indices]

    y_train = y[train_indices]

    x_test = x[test_indices]

    y_test = y[test_indices]

    if len(np.unique(y_train)) < 2:
        raise TrainingDataError("Training split does not contain both classes.")

    if len(np.unique(y_test)) < 2:
        raise TrainingDataError("Test split does not contain both classes.")

    LOGGER.info(
        "Training split: %d samples.",
        len(x_train),
    )

    LOGGER.info(
        "Test split: %d samples.",
        len(x_test),
    )

    model = build_model(config)

    LOGGER.info(
        "Training Random Forest with %d trees.",
        config.n_estimators,
    )

    model.fit(
        x_train,
        y_train,
    )

    probabilities = positive_probability(
        model,
        x_test,
    )

    selected_threshold = (
        select_threshold(
            y_test,
            probabilities,
            default=config.threshold,
        )
        if config.optimize_threshold
        else config.threshold
    )

    metrics = classification_metrics(
        y_test,
        probabilities,
        threshold=selected_threshold,
    )

    elapsed = time.monotonic() - started

    dataset_fp = ""

    try:
        dataset_fp = str(dataset_fingerprint(dataset))
    except Exception as exc:
        LOGGER.warning(
            "Unable to calculate dataset fingerprint: %s",
            exc,
        )

    schema_fp = calculate_schema_fingerprint(schema)

    metadata = build_model_metadata(
        config=config,
        model=model,
        dataset=dataset,
        schema=schema,
        metrics=metrics,
        selected_threshold=selected_threshold,
        train_samples=len(train_indices),
        test_samples=len(test_indices),
        positive_samples=positive_count,
        negative_samples=negative_count,
        dataset_fp=dataset_fp,
        schema_fp=schema_fp,
        training_seconds=elapsed,
    )

    thresholds = build_threshold_metadata(
        selected_threshold=selected_threshold,
        default_threshold=config.threshold,
        metrics=metrics,
        dataset_fp=dataset_fp,
        schema_fp=schema_fp,
    )

    save_training_artifacts(
        model=model,
        schema=schema,
        metadata=metadata,
        thresholds=thresholds,
        config=config,
    )

    result = TrainingResult(
        config=config,
        sample_count=int(x.shape[0]),
        feature_count=feature_count,
        train_samples=len(train_indices),
        test_samples=len(test_indices),
        positive_samples=positive_count,
        negative_samples=negative_count,
        dataset_fingerprint=dataset_fp,
        schema_fingerprint=schema_fp,
        selected_threshold=selected_threshold,
        metrics=metrics,
        model_path=config.model_path,
        schema_path=config.schema_path,
        metadata_path=config.metadata_path,
        thresholds_path=config.thresholds_path,
        training_seconds=elapsed,
        model=model,
    )

    LOGGER.info(
        "Training completed in %.2fs.",
        elapsed,
    )

    return result



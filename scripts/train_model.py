def save_model_artifact(
    model: Any,
    path: Path,
) -> None:
    if joblib is None:
        raise TrainingDependencyError("joblib is required to save the trained model.")

    ensure_parent(path)

    fd, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.",
        suffix=".tmp",
        dir=str(path.parent),
    )

    temporary_path = Path(temporary_name)

    try:
        os.close(fd)

        joblib.dump(
            model,
            temporary_path,
            compress=3,
        )

        os.replace(
            temporary_path,
            path,
        )

    except Exception as exc:
        try:
            temporary_path.unlink(missing_ok=True)
        except OSError:
            pass

        raise TrainingArtifactError(
            f"Unable to save model artifact {path}: {exc}"
        ) from exc


def save_training_artifacts(
    *,
    model: Any,
    schema: Any,
    metadata: Mapping[str, Any],
    thresholds: Mapping[str, Any],
    config: TrainingConfig,
) -> None:
    """
    Persist model, schema, metadata, and threshold artifacts atomically where
    possible.
    """

    if not config.overwrite and (
        config.model_path.exists()
        or config.schema_path.exists()
        or config.metadata_path.exists()
        or config.thresholds_path.exists()
    ):
        raise TrainingArtifactError(
            "One or more output artifacts already exist and "
            "--no-overwrite was selected."
        )

    try:
        save_model_artifact(
            model,
            config.model_path,
        )

        ensure_parent(config.schema_path)

        try:
            save_schema(
                schema,
                config.schema_path,
            )
        except Exception:
            # Fall back to deterministic JSON serialization when the dataset
            # layer's schema serializer is unavailable or incompatible.
            atomic_write_json(
                config.schema_path,
                schema_to_dict(schema),
            )

        atomic_write_json(
            config.metadata_path,
            metadata,
        )

        atomic_write_json(
            config.thresholds_path,
            thresholds,
        )

    except TrainingArtifactError:
        raise

    except Exception as exc:
        raise TrainingArtifactError(
            f"Unable to persist training artifacts: {exc}"
        ) from exc



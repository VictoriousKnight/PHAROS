def load_trained_model(
    path: Path = DEFAULT_MODEL_PATH,
) -> Any:
    """
    Load a trusted trained model artifact.

    WARNING:
        joblib deserialization can execute arbitrary Python code. Only use
        this function with model artifacts from a trusted source.
    """

    if joblib is None:
        raise TrainingDependencyError("joblib is required to load trained models.")

    path = Path(path)

    if not path.exists():
        raise TrainingArtifactError(f"Model artifact does not exist: {path}")

    if not path.is_file():
        raise TrainingArtifactError(f"Model artifact is not a regular file: {path}")

    try:
        model = joblib.load(path)
    except Exception as exc:
        raise TrainingArtifactError(
            f"Unable to load trained model {path}: {exc}"
        ) from exc

    if not hasattr(
        model,
        "predict",
    ):
        raise TrainingArtifactError("Loaded model does not expose predict().")

    if not hasattr(
        model,
        "predict_proba",
    ):
        raise TrainingArtifactError("Loaded model does not expose predict_proba().")

    return model



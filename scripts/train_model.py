def positive_probability(
    model: Any,
    x: Any,
) -> Any:
    if not hasattr(
        model,
        "predict_proba",
    ):
        raise TrainingError("Trained model does not expose predict_proba().")

    probabilities = model.predict_proba(x)

    probabilities = np.asarray(
        probabilities,
        dtype=np.float64,
    )

    if probabilities.ndim != 2:
        raise TrainingError("Model probability output is not two-dimensional.")

    classes = list(
        getattr(
            model,
            "classes_",
            [],
        )
    )

    if 1 in classes:
        positive_index = classes.index(1)
    elif "malicious" in classes:
        positive_index = classes.index("malicious")
    elif probabilities.shape[1] == 2:
        positive_index = 1
    else:
        raise TrainingError("Unable to identify positive class in model output.")

    return np.clip(
        probabilities[
            :,
            positive_index,
        ],
        0.0,
        1.0,
    )


def classification_metrics(
    y_true: Any,
    probabilities: Any,
    *,
    threshold: float,
) -> BinaryMetrics:
    y_true = np.asarray(
        y_true,
        dtype=np.int64,
    )

    probabilities = np.asarray(
        probabilities,
        dtype=np.float64,
    )

    predictions = (probabilities >= threshold).astype(np.int64)

    tn, fp, fn, tp = confusion_matrix(
        y_true,
        predictions,
        labels=[0, 1],
    ).ravel()

    specificity = float(tn) / float(tn + fp) if (tn + fp) else 0.0

    fpr = float(fp) / float(fp + tn) if (fp + tn) else 0.0

    fnr = float(fn) / float(fn + tp) if (fn + tp) else 0.0

    roc_auc: Optional[float]

    if len(np.unique(y_true)) == 2:
        try:
            roc_auc = float(
                roc_auc_score(
                    y_true,
                    probabilities,
                )
            )
        except Exception:
            roc_auc = None
    else:
        roc_auc = None

    average_precision: Optional[float]

    if len(np.unique(y_true)) == 2:
        try:
            average_precision = float(
                average_precision_score(
                    y_true,
                    probabilities,
                )
            )
        except Exception:
            average_precision = None
    else:
        average_precision = None

    return BinaryMetrics(
        threshold=float(threshold),
        samples=int(len(y_true)),
        accuracy=float(
            accuracy_score(
                y_true,
                predictions,
            )
        ),
        balanced_accuracy=float(
            balanced_accuracy_score(
                y_true,
                predictions,
            )
        ),
        precision=float(
            precision_score(
                y_true,
                predictions,
                zero_division=0,
            )
        ),
        recall=float(
            recall_score(
                y_true,
                predictions,
                zero_division=0,
            )
        ),
        f1=float(
            f1_score(
                y_true,
                predictions,
                zero_division=0,
            )
        ),
        specificity=specificity,
        false_positive_rate=fpr,
        false_negative_rate=fnr,
        roc_auc=roc_auc,
        average_precision=average_precision,
        true_negatives=int(tn),
        false_positives=int(fp),
        false_negatives=int(fn),
        true_positives=int(tp),
    )


def threshold_candidates(
    *,
    minimum: float = 0.05,
    maximum: float = 0.95,
    step: float = 0.01,
) -> list[float]:
    values: list[float] = []

    current = minimum

    while current <= maximum + 1e-12:
        values.append(
            round(
                current,
                4,
            )
        )

        current += step

    return values


def select_threshold(
    y_true: Any,
    probabilities: Any,
    *,
    default: float,
) -> float:
    """
    Select a deterministic operating threshold.

    The primary objective is F1. Balanced accuracy is used as the tie-breaker,
    followed by proximity to the default 0.50 threshold.
    """

    candidates = threshold_candidates()

    best_threshold = default
    best_key = (
        -1.0,
        -1.0,
        float("inf"),
    )

    for threshold in candidates:
        metrics = classification_metrics(
            y_true,
            probabilities,
            threshold=threshold,
        )

        key = (
            metrics.f1,
            metrics.balanced_accuracy,
            -abs(threshold - default),
        )

        if key > best_key:
            best_key = key
            best_threshold = threshold

    return float(best_threshold)



def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def safe_float(
    value: Any,
    default: float = 0.0,
) -> float:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return default

    if not math.isfinite(number):
        return default

    return number


def normalize_label(
    value: Any,
) -> str:
    text = str(value if value is not None else "").strip().lower()

    return text.replace(" ", "_").replace("-", "_")


def label_to_binary(
    value: Any,
) -> int:
    label = normalize_label(value)

    if label in POSITIVE_LABELS:
        return 1

    if label in NEGATIVE_LABELS:
        return 0

    raise TrainingDataError(
        f"Unsupported dataset label: {value!r}. " "Expected benign/0 or malicious/1."
    )


def sha256_bytes(
    value: bytes,
) -> str:
    return hashlib.sha256(value).hexdigest()


def sha256_json(
    value: Any,
) -> str:
    payload = json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        default=str,
    ).encode("utf-8")

    return sha256_bytes(payload)


def ensure_parent(
    path: Path,
) -> None:
    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )


def atomic_write_bytes(
    path: Path,
    data: bytes,
) -> None:
    ensure_parent(path)

    fd, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.",
        suffix=".tmp",
        dir=str(path.parent),
    )

    temporary_path = Path(temporary_name)

    try:
        with os.fdopen(
            fd,
            "wb",
        ) as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())

        os.replace(
            temporary_path,
            path,
        )

    except Exception:
        try:
            temporary_path.unlink(missing_ok=True)
        except OSError:
            pass

        raise


def atomic_write_json(
    path: Path,
    value: Any,
) -> None:
    payload = json.dumps(
        value,
        indent=2,
        sort_keys=True,
        ensure_ascii=False,
        default=str,
    ).encode("utf-8")

    atomic_write_bytes(
        path,
        payload + b"\n",
    )



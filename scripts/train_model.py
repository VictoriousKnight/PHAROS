def build_training_schema(
    records: Sequence[DatasetRecord],
) -> Any:
    try:
        schema = build_schema(records)
    except Exception as exc:
        raise TrainingDataError(f"Unable to build feature schema: {exc}") from exc

    if schema is None:
        raise TrainingDataError("Feature schema construction returned None.")

    feature_count = schema_feature_count(schema)

    if feature_count <= 0:
        raise TrainingDataError("Feature schema contains no features.")

    if feature_count > MAX_FEATURES:
        raise TrainingDataError(
            f"Feature count {feature_count:,} exceeds "
            f"the maximum allowed {MAX_FEATURES:,}."
        )

    return schema


def schema_feature_names(
    schema: Any,
) -> list[str]:
    """
    Extract feature names from the project's FeatureSchema.
    """

    if schema is None:
        return []

    if isinstance(
        schema,
        Mapping,
    ):
        for key in (
            "features",
            "feature_names",
            "definitions",
        ):
            value = schema.get(key)

            if isinstance(
                value,
                Mapping,
            ):
                names = [str(key) for key in value.keys()]

                if names:
                    return names

            if isinstance(
                value,
                Sequence,
            ) and not isinstance(
                value,
                (str, bytes),
            ):
                names: list[str] = []

                for item in value:
                    if isinstance(
                        item,
                        str,
                    ):
                        names.append(item)
                    elif isinstance(
                        item,
                        Mapping,
                    ):
                        name = item.get("name")

                        if name:
                            names.append(str(name))

                    elif hasattr(
                        item,
                        "name",
                    ):
                        names.append(str(item.name))

                if names:
                    return names

    for attribute in (
        "feature_names",
        "names",
        "features",
        "definitions",
    ):
        value = getattr(
            schema,
            attribute,
            None,
        )

        if isinstance(
            value,
            Mapping,
        ):
            names = [str(key) for key in value.keys()]

            if names:
                return names

        if isinstance(
            value,
            Sequence,
        ) and not isinstance(
            value,
            (str, bytes),
        ):
            names = []

            for item in value:
                if isinstance(
                    item,
                    str,
                ):
                    names.append(item)
                elif hasattr(
                    item,
                    "name",
                ):
                    names.append(str(item.name))
                elif isinstance(
                    item,
                    Mapping,
                ):
                    name = item.get("name")

                    if name:
                        names.append(str(name))

            if names:
                return names

    return []


def schema_feature_count(
    schema: Any,
) -> int:
    names = schema_feature_names(schema)

    if names:
        return len(names)

    if isinstance(
        schema,
        Mapping,
    ):
        for key in (
            "feature_count",
            "n_features",
            "count",
        ):
            value = schema.get(key)

            try:
                number = int(value)

                if number >= 0:
                    return number
            except (
                TypeError,
                ValueError,
            ):
                pass

    for attribute in (
        "feature_count",
        "n_features",
        "count",
    ):
        value = getattr(
            schema,
            attribute,
            None,
        )

        try:
            number = int(value)

            if number >= 0:
                return number
        except (
            TypeError,
            ValueError,
        ):
            pass

    return 0


def schema_to_dict(
    schema: Any,
) -> dict[str, Any]:
    if isinstance(
        schema,
        Mapping,
    ):
        return dict(schema)

    if is_dataclass(schema):
        return asdict(schema)

    if hasattr(
        schema,
        "to_dict",
    ):
        value = schema.to_dict()

        if isinstance(
            value,
            Mapping,
        ):
            return dict(value)

    result: dict[str, Any] = {}

    for attribute in (
        "name",
        "version",
        "feature_names",
        "features",
        "definitions",
        "feature_count",
        "n_features",
        "metadata",
    ):
        if hasattr(
            schema,
            attribute,
        ):
            result[attribute] = getattr(
                schema,
                attribute,
            )

    return result


